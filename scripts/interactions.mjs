// Behaviour axe cannot see: keyboard paths and where focus lands. Runs against
// a built Storybook.
//
//   npm run build-storybook && npm run test:interactions
import { createReadStream, existsSync } from "node:fs"
import { createServer } from "node:http"
import { extname, join, resolve } from "node:path"
import { chromium } from "playwright"

const ROOT = resolve(process.argv[2] ?? "storybook-static")
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json", ".svg": "image/svg+xml" }
const server = createServer((req, res) => {
  const path = join(ROOT, decodeURIComponent(new URL(req.url, "http://x").pathname))
  if (!path.startsWith(ROOT) || !existsSync(path)) { res.writeHead(404); return res.end() }
  res.writeHead(200, { "content-type": TYPES[extname(path)] ?? "application/octet-stream" })
  createReadStream(path).pipe(res)
})
await new Promise((ok) => server.listen(0, ok))
const base = `http://localhost:${server.address().port}`
const browser = await chromium.launch(process.env.CI ? {} : { channel: "chrome" })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })

const open = async (id, mode = "story") => {
  await page.goto(`${base}/iframe.html?id=${id}&viewMode=${mode}`)
  await page.waitForFunction(() => (document.querySelector("#storybook-root")?.childElementCount > 0) || document.querySelector("#storybook-docs")?.childElementCount > 0)
  await page.waitForTimeout(200)
}
const focused = () => page.evaluate(() => (document.activeElement?.getAttribute("aria-label") || document.activeElement?.textContent || "").trim())
const results = []
const test = async (name, fn) => {
  if (process.env.TRACE) console.error(name)
  try { await fn(); results.push(["ok", name]) } catch (e) { results.push(["FAIL", `${name}: ${String(e.message).split("\n")[0]}`]) }
}
const eq = (got, want, what) => { if (got !== want) throw new Error(`${what}: expected "${want}", got "${got}"`) }

